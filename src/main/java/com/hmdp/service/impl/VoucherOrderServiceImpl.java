    @Override
    public Result applyRefund(Long orderId, String reason) {
        Long userId = UserHolder.getUser().getId();
        VoucherOrder order = getById(orderId);
        if (order == null) return Result.fail("订单不存在");
        if (!order.getUserId().equals(userId)) return Result.fail("无权操作该订单");
        // 仅已支付(2)/已核销(3)可申请退款
        Integer st = order.getStatus();
        if (st == null || (st != 2 && st != 3)) {
            return Result.fail("当前订单状态不支持退款申请");
        }
        order.setStatus(5);
        order.setRefundReason(reason);
        order.setRefundApplyTime(java.time.LocalDateTime.now());
        order.setUpdateTime(java.time.LocalDateTime.now());
        updateById(order);
        return Result.ok(orderId);
    }

